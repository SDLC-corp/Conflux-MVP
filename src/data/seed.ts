function chainAudit(events: Omit<AuditEvent, "hash" | "prevHash">[]): AuditEvent[] {
  // events given oldest-first; stored newest-first
  let prev = "0000000000000000";
  const out: AuditEvent[] = [];
  for (const e of events) {
    const h = hash(prev + JSON.stringify(e));
    out.push({ ...e, prevHash: prev, hash: h });
    prev = h;
  }
  return out.reverse();
}

